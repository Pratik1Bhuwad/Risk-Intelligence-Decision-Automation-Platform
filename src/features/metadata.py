def get_feature_catalog_df() -> pd.DataFrame:
    """Return the feature catalog as a pandas DataFrame."""
    records = []
    for f in FEATURE_CATALOG.values():
        records.append(
            {
                "feature_name": f.name,
                "group": f.group,
                "definition": f.definition,
                "formula": f.formula,
                "source_fields": ", ".join(f.source_fields),
                "entity_grain": f.entity_grain,
                "time_window": f.time_window,
                "data_type": f.data_type,
                "null_handling": f.null_handling,
                "leakage_risk": f.leakage_risk,
                "expected_coverage": f.expected_coverage,
                "status": f.status,
                "model_value": f.model_value,
            }
        )
    return pd.DataFrame(records)
